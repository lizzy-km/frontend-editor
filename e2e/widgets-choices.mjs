// A filter whose choices come from another data source (a categories list) and match a field of the table's items.
import { check, inspectorTab, openAddFolds, openExample } from './browser.mjs'

const { browser, page, errors } = await openExample()
await page.waitForTimeout(800)
const side = page.locator('aside').first()
const settings = page.locator('aside').last()
await side.getByRole('tab', { name: 'Data' }).click()
for (const preset of ['Store products (Fake Store API)', 'Categories (for filters)']) {
  await side.getByLabel('Start from').selectOption(preset)
  await side.getByRole('button', { name: 'Add data' }).click()
  await page.waitForTimeout(300)
}
await side.getByRole('tab', { name: 'Add' }).click()
await openAddFolds(page)
const add = async (name) => {
  await page.evaluate(() => document.activeElement?.blur())
  for (let i = 0; i < 3; i++) await page.keyboard.press('Escape')
  await side.getByRole('button', { name, exact: true }).click()
  await page.waitForTimeout(400)
}
await add('Table from data')
await add('Filter buttons')
await inspectorTab(page, 'Actions')
await settings.getByLabel('Filter by').selectOption('category')
await page.waitForTimeout(300)
const sources = await settings.getByLabel('Choices from').locator('option').allInnerTexts()
check('the filter can take its choices from another list', sources.some((text) => text.includes('categories')), sources.join(' | '))
await settings.getByLabel('Choices from').selectOption('categories')
await page.waitForTimeout(400)
check('the words come from the list’s text field', (await settings.getByLabel('Choice words from').inputValue()) === 'name')

await page.getByRole('button', { name: 'Preview' }).click()
const view = page.frameLocator('iframe[title="Preview of your page"]')
await view.locator('[data-ui="filter"]').first().waitFor()
const rows = () => view.locator('table[data-ui="table"] tbody tr:visible').count()
const chips = await view.locator('[data-ui="filter"] [data-ui-filter]').allInnerTexts()
check('buttons: All and one for each category', chips.join('|') === "All|electronics|jewelery|men's clothing|women's clothing", chips.join('|'))
check('every item shows at first', (await rows()) === 5, String(await rows()))
await view.locator('[data-ui="filter"] [data-ui-filter="men\'s clothing"]').click()
check('a category keeps the items of that category', (await rows()) === 4, String(await rows()))
await view.locator('[data-ui="filter"] [data-ui-filter="jewelery"]').click()
check('another category keeps its own', (await rows()) === 1, String(await rows()))
await view.locator('[data-ui="filter"] [data-ui-filter="women\'s clothing"]').click()
check('a category without items shows none', (await rows()) === 0, String(await rows()))
await view.locator('[data-ui="filter"] [data-ui-filter=""]').click()
check('All shows everything again', (await rows()) === 5)
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
