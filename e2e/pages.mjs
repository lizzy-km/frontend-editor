// Multi-page sites: add pages (empty, pasted, copy), switch, rename, undo, delete. Header/footer are shared.
import { check, OUT, openExample, inspectorTab } from './browser.mjs'

const { browser, page, frame, box, errors } = await openExample()
const sidebar = page.locator('aside').first()
const visible = (selector) => frame.$eval(selector, (el) => el.getClientRects().length > 0).catch(() => false)
const pageList = () => sidebar.getByRole('list', { name: 'Pages' }).getByRole('listitem')

check('one-page projects have no Pages tab', (await sidebar.getByRole('tab', { name: 'Pages' }).count()) === 0)
// Click empty space on the page (selects the page itself), then turn it into a website
const frameBox = await page.locator('iframe[title="Your page"]').boundingBox()
await page.mouse.move(frameBox.x + frameBox.width / 2, frameBox.y + frameBox.height - 30)
await page.mouse.click(frameBox.x + frameBox.width / 2, frameBox.y + frameBox.height - 30)
await page.waitForTimeout(300)
await page.locator('aside').last().getByRole('button', { name: /Make this a website/ }).click()
await page.waitForTimeout(300)
check('"Make this a website" opens the Pages tab with Home', (await pageList().count()) === 1 && (await pageList().first().textContent()).includes('Home'))

// Empty page
await sidebar.getByRole('button', { name: 'Add a page' }).click()
await page.getByRole('dialog').getByLabel('Page name').fill('About us')
await page.getByRole('button', { name: 'Add page' }).click()
await page.waitForTimeout(500)
check('site now has Home and About us', (await pageList().count()) === 2)
check('new page shows, Home hides, header stays', (await frame.$eval('body', (b) => b.innerText)).includes('About us') && !(await visible('.hero')) && (await visible('nav')))
await page.screenshot({ path: OUT + 'pages-about.png' })

// Pasted page: its own header and footer are dropped
await sidebar.getByRole('button', { name: 'Add a page' }).click()
await page.getByRole('dialog').getByLabel('Page name').fill('Prices')
await page.getByRole('group', { name: 'Start with' }).getByRole('button', { name: 'Paste code' }).click()
const code = page.locator('.cm-editor', { has: page.getByLabel('Code for the new page') })
await code.waitFor()
await code.locator('.cm-content').click()
await page.keyboard.insertText('<header>Other header</header><section class="prices"><h2>Plans</h2></section>')
await page.getByRole('button', { name: 'Add page' }).click()
await page.waitForTimeout(500)
check('pasted page added without its own header', (await visible('.prices')) && (await frame.$$eval('header', (all) => all.filter((h) => h.innerText.includes('Other header')).length)) === 0)

// Switch back, rename, address
await sidebar.getByRole('button', { name: /^Home/ }).click()
await page.waitForTimeout(300)
check('switching shows Home again', (await visible('.hero')) && !(await visible('.prices')))
await sidebar.getByLabel('Page name').fill('Start')
await sidebar.getByLabel('Page name').press('Enter')
await page.waitForTimeout(200)
check('rename shows in the list', (await pageList().first().textContent()).includes('Start'))

const layers = await (async () => { await sidebar.getByRole('tab', { name: 'Layers' }).click(); return sidebar.getByRole('tree').textContent() })()
check('layers show the current page only', layers.includes('Page “Start”') && !layers.includes('Page “Prices”'))

// Undo the rename, then delete Prices
await page.mouse.click(700, 845)
await page.keyboard.press('Control+z')
await sidebar.getByRole('tab', { name: 'Pages' }).click()
check('undo brings the old name back', (await pageList().first().textContent()).includes('Home'))
page.once('dialog', (dialog) => dialog.accept())
await sidebar.getByRole('button', { name: 'Delete Prices' }).click()
await page.waitForTimeout(300)
check('page deleted', (await pageList().count()) === 2)
// A nav link goes to a page; in Preview, clicking it opens that page
const link = await box('nav a:last-child')
await page.mouse.move(link.x + 4, link.y + 4)
await page.mouse.click(link.x + 4, link.y + 4)
await page.waitForTimeout(300)
await inspectorTab(page, 'Actions')
await page.locator('aside').last().getByLabel('Link to a page').selectOption('/about-us')
await page.waitForTimeout(300)
check('link set to the About us page', (await frame.$eval('nav a:last-child', (a) => a.getAttribute('href'))) === '/about-us')
await page.getByRole('button', { name: 'Preview' }).click()
const preview = page.frameLocator('iframe[title="Preview of your page"]')
await preview.locator('nav a:last-child').click()
await page.waitForTimeout(600)
check('Preview opens the linked page', (await preview.locator('body').innerText()).includes('About us'))
await page.getByRole('button', { name: 'Back to editing' }).click()

// A whole box can open a page too ("Click goes to")
await page.locator('aside').first().getByRole('tab', { name: 'Pages' }).click()
await page.locator('aside').first().getByRole('button', { name: /^Home/ }).click()
await page.waitForTimeout(300)
const hero = await box('.hero')
await page.mouse.move(hero.x + 6, hero.y + 6)
await page.mouse.click(hero.x + 6, hero.y + 6)
await page.waitForTimeout(300)
await inspectorTab(page, 'Actions')
await page.locator('aside').last().getByRole('button', { name: 'Click goes to' }).click()
await page.locator('aside').last().getByLabel('Click goes to page').selectOption('/about-us')
await page.waitForTimeout(200)
await page.getByRole('button', { name: 'Preview' }).click()
const preview2 = page.frameLocator('iframe[title="Preview of your page"]')
await preview2.locator('.hero h1').click()
await page.waitForTimeout(600)
check('clicking a "click goes to" box opens its page in Preview', (await preview2.locator('body').innerText()).includes('About us'))
await page.getByRole('button', { name: 'Back to editing' }).click()
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
