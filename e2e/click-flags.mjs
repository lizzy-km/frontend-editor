// "When clicked → Flag": pick a flag (added under Who can see this) and what a click does to it. The behavior itself is unit tested.
import { check, openExample, inspectorTab, openAddFolds } from './browser.mjs'

const { browser, page, frame, box, errors } = await openExample()
const sidebar = page.locator('aside').first()
const panel = page.locator('aside').last()

await page.mouse.click(12, 845)
await sidebar.getByRole('tab', { name: 'Add' }).click()
await openAddFolds(page)
await sidebar.getByRole('button', { name: 'Pop-up', exact: true }).click()
await page.waitForTimeout(600)
await frame.evaluate(() => document.querySelector('[data-fe-open]').scrollIntoView({ block: 'center' }))
await page.waitForTimeout(300)
const button = await box('[data-fe-open]')
await page.mouse.click(button.x + 6, button.y + 6)
await page.waitForTimeout(300)
await inspectorTab(page, 'Actions')

await panel.getByRole('button', { name: 'Who can see this' }).click()
await panel.getByLabel('New flag').fill('beta')
await panel.getByLabel('New flag').press('Enter')
await page.waitForTimeout(300)
await panel.getByLabel('Flag to change').selectOption('beta')
await page.waitForTimeout(300)
check('the flag is saved on the button', (await frame.$eval('[data-fe-open]', (el) => el.getAttribute('data-fe-flag'))) === 'beta')
check('a click switches it by default', (await frame.$eval('[data-fe-open]', (el) => el.getAttribute('data-fe-flag-mode'))) === 'toggle')
await panel.getByLabel('What happens to the flag').selectOption('on')
await page.waitForTimeout(300)
check('the choice "turn it on" is saved', (await frame.$eval('[data-fe-open]', (el) => el.getAttribute('data-fe-flag-mode'))) === 'on')
await panel.getByLabel('Flag to change').selectOption('')
await page.waitForTimeout(300)
check('choosing Nothing removes it', (await frame.$eval('[data-fe-open]', (el) => el.hasAttribute('data-fe-flag') || el.hasAttribute('data-fe-flag-mode'))) === false)
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
