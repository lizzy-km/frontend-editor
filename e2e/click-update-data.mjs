// "When clicked → Update data": pick a connected data source, which item and what changes. The requests themselves are unit tested.
import { check, openExample, inspectorTab, openAddFolds } from './browser.mjs'

const { browser, page, frame, box, errors } = await openExample()
const sidebar = page.locator('aside').first()
const panel = page.locator('aside').last()
const patches = []
await page.route('https://api.example.test/**', async (route) => {
  const cors = { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*' }
  if (route.request().method() === 'OPTIONS') return route.fulfill({ status: 204, headers: { ...cors, 'access-control-allow-methods': '*' } })
  if (route.request().method() === 'PATCH') { patches.push({ url: route.request().url(), body: route.request().postData() }); return route.fulfill({ status: 200, headers: cors, contentType: 'application/json', body: '{}' }) }
  route.fulfill({ status: 200, headers: cors, contentType: 'application/json', body: JSON.stringify([
    { id: 1, title: 'Alpha', price: 10, liked: false, image: 'https://img.test/a.jpg' }, { id: 2, title: 'Beta', price: 20, liked: true, image: 'https://img.test/b.jpg' }]) })
})

await page.route('https://img.test/**', (route) => route.fulfill({ status: 200, contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4"/>' }))
await sidebar.getByRole('tab', { name: 'Data' }).click()
await sidebar.getByLabel('Start from').selectOption('Products')
await sidebar.getByRole('button', { name: 'Add data' }).click()
await sidebar.getByRole('button', { name: 'Connect your API' }).click()
const dialog = page.getByRole('dialog')
await dialog.getByLabel('Address for the list').fill('https://api.example.test/items')
await dialog.getByRole('button', { name: 'Test connection' }).click()
await page.waitForTimeout(800)
await dialog.getByRole('button', { name: /^Use these/ }).click()
await page.waitForTimeout(500)

await page.mouse.click(12, 845)
await sidebar.getByRole('tab', { name: 'Add' }).click()
await openAddFolds(page)
await sidebar.getByRole('button', { name: 'List from data' }).click()
await page.waitForTimeout(700)
await frame.evaluate(() => document.querySelector('[data-fe-list]').scrollIntoView({ block: 'center' }))
await page.waitForTimeout(300)
const heading = await box('[data-fe-list] > article:first-child h3')
await page.mouse.click(heading.x + 4, heading.y + 4)
await page.waitForTimeout(300)
await inspectorTab(page, 'Actions')

const attr = () => frame.$eval('[data-fe-list] > article:first-child h3', (el) => el.getAttribute('data-fe-update'))
await panel.getByRole('button', { name: 'When clicked' }).click()
await panel.getByLabel('Data to update').selectOption('products')
await page.waitForTimeout(300)
check('choosing the data inside a card updates "the clicked item" by default', (await attr()).includes('"source":"products"') && (await attr()).includes('"item":"clicked"'), await attr())
check('the card option is offered', (await panel.getByLabel('Which item to update').inputValue()) === 'clicked')
await panel.getByLabel('Field to change 1').selectOption('liked')
await page.waitForTimeout(200)
check('yes / no fields can be switched', await panel.getByLabel('What to do 1').locator('option', { hasText: 'Switch yes / no' }).count() === 1)
await panel.getByLabel('What to do 1').selectOption('toggle')
await page.waitForTimeout(300)
check('the change is saved', (await attr()).includes('"field":"liked","op":"toggle"'), await attr())
await panel.getByRole('button', { name: 'Add another change' }).click()
await page.waitForTimeout(300)
check('a second change row appears', await panel.getByLabel('Field to change 2').isVisible())

await panel.getByLabel('Which item to update').selectOption('id')
await page.waitForTimeout(200)
await panel.getByLabel('Id of the item to update').fill('7')
await panel.getByLabel('Id of the item to update').press('Enter')
await page.waitForTimeout(300)
check('one item by its id is saved', (await attr()).includes('"item":{"id":"7"}'), await attr())
check('only "Set to" is left for a chosen item', (await panel.getByLabel('What to do 1').locator('option').allTextContents()).join('|') === 'Set to')

await panel.getByLabel('Data to update').selectOption('')
await page.waitForTimeout(300)
check('choosing Nothing removes it', (await attr()) === null)
// Visitors: Preview sends the change for the clicked card's item and shows the new words
await panel.getByLabel('Data to update').selectOption('products')
await page.waitForTimeout(300)
await panel.getByLabel('Value 1').fill('Sold')
await panel.getByLabel('Value 1').press('Enter')
await page.waitForTimeout(300)
await page.getByRole('button', { name: 'Preview' }).click()
const preview = page.frameLocator('iframe[title="Preview of your page"]')
await preview.locator('[data-fe-list] h3').first().click()
await page.waitForTimeout(800)
check('Preview sends a PATCH for that item to its address', patches.length === 1 && patches[0].url === 'https://api.example.test/items/1', JSON.stringify(patches))
check('with the change as the body', patches[0]?.body === '{"title":"Sold"}', patches[0]?.body)
check('the card then shows the new words', (await preview.locator('[data-fe-list] h3').first().innerText()) === 'Sold')
check('no console errors', errors.length === 0, errors.join(' | '))
await browser.close()
