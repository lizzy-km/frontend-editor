// Showcase examples: the features each one claims really work for visitors in Preview.
import { check, openPage } from './browser.mjs'

/** Opens one example in Preview. */
async function preview(id) {
  const { browser, page, errors } = await openPage('/try')
  await page.waitForTimeout(800)
  await page.getByText('No idea yet? Start from a finished example').click()
  await page.locator(`[data-showcase="${id}"]`).getByRole('button', { name: 'Open this example' }).click()
  await page.waitForSelector('iframe[title="Your page"]')
  await page.waitForTimeout(2000)
  await page.getByRole('button', { name: 'Preview' }).click()
  await page.waitForTimeout(2000)
  const view = page.frameLocator('iframe[title="Preview of your page"]')
  const go = async (name) => { await view.getByRole('link', { name, exact: true }).first().click(); await page.waitForTimeout(1200) }
  return { browser, page, view, go, errors }
}
const visibleCount = (locator) => locator.evaluateAll((all) => all.filter((el) => el.getClientRects().length > 0 && getComputedStyle(el).display !== 'none').length)

// ---- Online shop
{
  const { browser, page, view, go } = await preview('shop')
  process.on('unhandledRejection', (error) => { console.log('FAIL  test crashed:', String(error.message).slice(0, 400).replace(/\s+/g, ' ')); process.exit(1) })
  check('shop: home shows featured products from data', (await visibleCount(view.locator('[data-fe-list] > *'))) >= 3)
  await go('Shop')
  const cards = view.locator('[data-fe-list] [data-fe-item]')
  const all = await visibleCount(cards)
  check('shop: the shop page lists all the products', all >= 12, String(all))
  await view.getByRole('searchbox').or(view.locator('input[type=search], [data-ui="search"] input')).first().fill('classic')
  await page.waitForTimeout(600)
  const found = await visibleCount(cards)
  check('shop: searching narrows the list', found > 0 && found < all, `${found} of ${all}`)
  await view.locator('input[type=search], [data-ui="search"] input').first().fill('')
  await page.waitForTimeout(400)
  const chips = view.locator('[data-ui="filter"] button, [data-ui-by] button')
  check('shop: category buttons come from the categories data', (await chips.count()) >= 5, String(await chips.count()))
  await chips.filter({ hasText: 'Shoes' }).first().click()
  await page.waitForTimeout(600)
  const shoes = await visibleCount(cards)
  check('shop: a category button narrows the list', shoes > 0 && shoes < all, `${shoes} of ${all}`)
  await view.getByRole('button', { name: /quick look/i }).locator('visible=true').first().click()
  await page.waitForTimeout(600)
  check('shop: Quick look opens a pop-up with that product', (await view.locator('[data-fe-modal="quick"]').first().isVisible()) && (await view.locator('[data-fe-modal="quick"] h2, [data-fe-modal="quick"] h3').first().innerText()).length > 3)
  await view.locator('[data-fe-modal="quick"] [data-fe-close]').first().click()
  await page.waitForTimeout(400)
  await view.locator('[data-fe-flag="favourites"]:visible').first().click()
  await page.waitForTimeout(400)
  check('shop: the heart switches on the favourites flag (a box appears)', (await visibleCount(view.locator('[data-fe-flags="favourites"]'))) > 0)
  await view.locator('[data-fe-list] [data-fe-item]:visible').first().locator('h3, h2').first().click()
  await page.waitForTimeout(1200)
  check('shop: clicking a card opens that product\'s own page', (await view.locator('[data-fe-record="products"] h1').first().innerText()).length > 3)
  await browser.close()
}

// ---- Cafe
{
  const { browser, page, view, go } = await preview('cafe')
  check('cafe: home has tabs that switch', await view.locator('[data-ui="tabs"] [data-ui-tab]').count() >= 2)
  const tabs = view.locator('[data-ui="tabs"] [data-ui-tab]')
  const before = await view.locator('[data-ui="tabs"] [data-ui-panel]:not([hidden])').first().innerText()
  await tabs.nth(1).click()
  await page.waitForTimeout(400)
  check('cafe: a tab shows its own panel', (await view.locator('[data-ui="tabs"] [data-ui-panel]:not([hidden])').first().innerText()) !== before)
  await go('Menu')
  const dishes = view.locator('[data-fe-list="menu"] [data-fe-item], [data-fe-list="menu"] > article')
  const total = await visibleCount(dishes)
  check('cafe: the menu lists the dishes', total >= 12, String(total))
  await view.locator('input[type=search], [data-ui="search"] input').first().fill('egg')
  await page.waitForTimeout(600)
  const eggs = await visibleCount(dishes)
  check('cafe: search narrows the menu', eggs > 0 && eggs < total, `${eggs} of ${total}`)
  await view.locator('input[type=search], [data-ui="search"] input').first().fill('')
  await view.locator('[data-ui-by="category"] button').filter({ hasText: 'Drinks' }).first().click()
  await page.waitForTimeout(600)
  const drinks = await visibleCount(dishes)
  check('cafe: a category button narrows the menu', drinks > 0 && drinks < total, `${drinks} of ${total}`)
  await view.locator('[data-fe-list="menu"] [data-fe-item]:visible, [data-fe-list="menu"] > article:visible').first().click()
  await page.waitForTimeout(600)
  check('cafe: a dish opens a pop-up with that dish', await view.locator('[data-fe-modal="dish"]').first().isVisible())
  await view.locator('[data-fe-modal="dish"] [data-fe-close]').first().click()
  await go('Reservations')
  check('cafe: the booking form has a date picker, guests and a time', (await view.locator('[data-ui="datepicker"]').count()) >= 1 && (await view.locator('[name="guests"]').count()) >= 1 && (await view.locator('[name="time"]').count()) >= 1)
  await browser.close()
}

// ---- Studio portfolio
{
  const { browser, page, view, go } = await preview('agency')
  await view.getByRole('button', { name: /showreel/i }).first().click()
  await page.waitForTimeout(500)
  check('agency: the showreel button opens a pop-up', await view.locator('[data-fe-modal="showreel"]').first().isVisible())
  await view.locator('[data-fe-modal="showreel"] [data-fe-close]').first().click()
  await go('Work')
  const projects = view.locator('[data-fe-list="projects"] > *')
  const all = await visibleCount(projects)
  check('agency: the work page lists the projects', all >= 8, String(all))
  await view.locator('[data-ui-by="category"] button').filter({ hasText: 'Web' }).first().click()
  await page.waitForTimeout(600)
  const web = await visibleCount(projects)
  check('agency: a category button narrows the projects', web > 0 && web < all, `${web} of ${all}`)
  await view.locator('[data-fe-list="projects"] > *:visible').first().click()
  await page.waitForTimeout(1200)
  check('agency: a project card opens its own page', (await view.locator('[data-fe-record="projects"] h1').first().innerText()).length > 3)
  await go('Team')
  check('agency: the team page shows four members (copies of one component) and leaves the main component out', (await view.locator('[data-fe-instance]').count()) + (await visibleCount(view.locator('.ag-member, [class*="member"]'))) >= 4 && (await view.locator('[data-fe-component]').count()) === 0)
  await go('Services')
  check('agency: the services page has tabs and a table', (await view.locator('[data-ui="tabs"]').count()) >= 1 && (await view.locator('table').count()) >= 1)
  await browser.close()
}

// ---- Members and SaaS
{
  const { browser, page, view, go } = await preview('members')
  check('members: a signed-out visitor sees "Start free" and not "Go to dashboard"', (await view.getByRole('link', { name: /start free/i }).count()) >= 1 && (await view.getByRole('link', { name: /go to dashboard/i }).count()) === 0)
  await view.locator('[data-fe-open="signup"]').first().click()
  await page.waitForTimeout(400)
  check('members: the sign-up button opens a pop-up with a form', (await view.locator('[data-fe-modal="signup"]').first().isVisible()) && (await view.locator('[data-fe-modal="signup"] form').count()) === 1)
  await view.locator('[data-fe-modal="signup"] [data-fe-close]').first().click()
  await page.waitForTimeout(400)
  await go('Pricing')
  check('members: pricing has Monthly and Yearly tabs', (await view.locator('[data-ui="tabs"] [data-ui-tab]').count()) >= 2)
  await go('What is new')
  const beta = view.locator('[data-fe-flags="beta"]').first()
  check('members: the beta box is hidden until the flag is switched on', !(await beta.isVisible()))
  await view.locator('[data-fe-flag="beta"]').first().click()
  await page.waitForTimeout(400)
  check('members: switching the beta flag shows the box', await beta.isVisible())
  await browser.close()
}
